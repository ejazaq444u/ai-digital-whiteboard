import React, { useState } from 'react';
import { useWhiteboard } from '../../context/WhiteboardContext';
import { jsPDF } from 'jspdf';
import {
  Download,
  FileText,
  Image as ImageIcon,
  CheckCircle,
  FileCode,
  X,
  Split,
  Eye
} from 'lucide-react';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const ExportModal: React.FC<ExportModalProps> = ({ isOpen, onClose }) => {
  const { board, activePage } = useWhiteboard();
  const [exportFormat, setExportFormat] = useState<'pdf' | 'png' | 'jpg' | 'json'>('pdf');
  const [contentMode, setContentMode] = useState<'clean' | 'original' | 'comparison'>('clean');
  const [isExporting, setIsExporting] = useState<boolean>(false);

  if (!isOpen || !board) return null;

  const handleExport = async () => {
    setIsExporting(true);

    try {
      const canvasElement = document.querySelector('canvas') as HTMLCanvasElement;
      if (!canvasElement) {
        alert('Canvas not ready for export.');
        setIsExporting(false);
        return;
      }

      if (exportFormat === 'json') {
        // Export project data
        const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(board, null, 2));
        const downloadAnchor = document.createElement('a');
        downloadAnchor.setAttribute("href", dataStr);
        downloadAnchor.setAttribute("download", `${board.title.replace(/\s+/g, '_')}_Lesson.json`);
        document.body.appendChild(downloadAnchor);
        downloadAnchor.click();
        downloadAnchor.remove();
        onClose();
        return;
      }

      if (exportFormat === 'png' || exportFormat === 'jpg') {
        const mime = exportFormat === 'png' ? 'image/png' : 'image/jpeg';
        const imgData = canvasElement.toDataURL(mime, 0.95);
        const link = document.createElement('a');
        link.download = `${board.title.replace(/\s+/g, '_')}_${activePage?.title || 'Page'}.${exportFormat}`;
        link.href = imgData;
        link.click();
        onClose();
        return;
      }

      if (exportFormat === 'pdf') {
        // Multi-page PDF generation
        const pdf = new jsPDF({
          orientation: 'landscape',
          unit: 'px',
          format: [canvasElement.width / 2, canvasElement.height / 2]
        });

        const imgData = canvasElement.toDataURL('image/png', 0.95);
        pdf.addImage(imgData, 'PNG', 0, 0, canvasElement.width / 2, canvasElement.height / 2);

        // Add lesson metadata page footer
        pdf.setFontSize(10);
        pdf.setTextColor(150, 150, 150);
        pdf.text(
          `Generated by AI Math & English Digital Whiteboard • Room: ${board.roomCode} • ${board.title}`,
          20,
          canvasElement.height / 2 - 15
        );

        pdf.save(`${board.title.replace(/\s+/g, '_')}_Lesson.pdf`);
        onClose();
      }
    } catch (err: any) {
      console.error('Export failed:', err);
      alert('Failed to export: ' + err.message);
    } finally {
      setIsExporting(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-sm p-4 animate-in fade-in">
      <div className="bg-slate-800 border border-slate-700 rounded-2xl w-full max-w-lg shadow-2xl overflow-hidden flex flex-col text-slate-100">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-700 bg-slate-800/80">
          <div className="flex items-center space-x-3">
            <div className="p-2 bg-sky-500/20 text-sky-400 rounded-xl">
              <Download className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold">Export Whiteboard Lesson</h3>
              <p className="text-xs text-slate-400">Classroom ready PDF, images, or project file</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-white rounded-lg hover:bg-slate-700 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Body */}
        <div className="p-6 space-y-5">
          {/* Export Format */}
          <div className="space-y-2">
            <label className="text-xs font-bold text-slate-400 uppercase tracking-wider">
              Export Format
            </label>
            <div className="grid grid-cols-4 gap-2">
              {[
                { id: 'pdf', label: 'PDF Document', icon: <FileText className="w-4 h-4" /> },
                { id: 'png', label: 'PNG Image', icon: <ImageIcon className="w-4 h-4" /> },
                { id: 'jpg', label: 'JPG Image', icon: <ImageIcon className="w-4 h-4" /> },
                { id: 'json', label: 'JSON Project', icon: <FileCode className="w-4 h-4" /> }
              ].map(f => (
                <button
                  key={f.id}
                  onClick={() => setExportFormat(f.id as any)}
                  className={`p-3 rounded-xl border flex flex-col items-center justify-center space-y-1 transition-all ${
                    exportFormat === f.id
                      ? 'bg-sky-500/20 border-sky-500 text-sky-200 font-bold'
                      : 'bg-slate-900/60 border-slate-700 text-slate-400 hover:border-slate-600'
                  }`}
                >
                  {f.icon}
                  <span className="text-xs">{f.label}</span>
                </button>
              ))}
            </div>
          </div>

          {/* Clean vs Original Handwriting Mode */}
          <div className="space-y-2">
            <label className="text-xs font-bold text-slate-400 uppercase tracking-wider">
              Handwriting Content Mode
            </label>
            <div className="grid grid-cols-3 gap-2">
              {[
                {
                  id: 'clean',
                  label: 'Clean Accepted',
                  desc: 'Formatted KaTeX & neat fonts (Default)',
                  icon: <CheckCircle className="w-4 h-4 text-emerald-400" />
                },
                {
                  id: 'original',
                  label: 'Original Handwriting',
                  desc: 'Preserve raw pen strokes',
                  icon: <Eye className="w-4 h-4 text-amber-400" />
                },
                {
                  id: 'comparison',
                  label: 'Show Both',
                  desc: 'Side-by-side verification',
                  icon: <Split className="w-4 h-4 text-sky-400" />
                }
              ].map(m => (
                <button
                  key={m.id}
                  onClick={() => setContentMode(m.id as any)}
                  className={`p-3 rounded-xl border text-left transition-all ${
                    contentMode === m.id
                      ? 'bg-sky-500/20 border-sky-500 text-sky-200'
                      : 'bg-slate-900/60 border-slate-700 hover:border-slate-600'
                  }`}
                >
                  <div className="flex items-center space-x-1.5 font-bold text-xs">
                    {m.icon}
                    <span>{m.label}</span>
                  </div>
                  <div className="text-[11px] text-slate-400 mt-1">{m.desc}</div>
                </button>
              ))}
            </div>
          </div>

          <div className="p-3 bg-slate-900/80 border border-slate-700/80 rounded-xl text-xs text-slate-300">
            <span className="font-semibold text-slate-100">Pages included:</span> All {board.pages.length} pages will be rendered at crisp high resolution with mathematics and neat handwriting preserved.
          </div>
        </div>

        {/* Footer */}
        <div className="px-6 py-4 border-t border-slate-700 bg-slate-800/80 flex items-center justify-between">
          <button
            onClick={onClose}
            className="px-4 py-2 text-slate-400 hover:text-white text-xs font-medium rounded-xl hover:bg-slate-700 transition-colors"
          >
            Cancel
          </button>
          <button
            onClick={handleExport}
            disabled={isExporting}
            className="flex items-center space-x-2 px-6 py-2 bg-gradient-to-r from-sky-500 to-indigo-600 hover:from-sky-400 hover:to-indigo-500 text-white font-bold text-xs rounded-xl shadow-lg transition-all disabled:opacity-50"
          >
            <Download className="w-4 h-4" />
            <span>{isExporting ? 'Generating Document...' : `Download ${exportFormat.toUpperCase()}`}</span>
          </button>
        </div>
      </div>
    </div>
  );
};
